package com.datingsite.model;

/**
 * Перечисление ролей пользователей в системе сайта знакомств.
 */
public enum Role {

    /**
     * Администратор системы с полными правами управления.
     */
    ADMIN,
    /**
     * Модератор системы для проверки анкет и контента.
     */
    MODERATOR,
    /**
     * Обычный зарегистрированный пользователь.
     */
    USER
}
